-- =====================================================================
-- 修复字符集乱码历史数据 + 清理 CRUD 测试残留数据
-- 说明：历史数据中部分中文已被存为 '?'（0x3F），无法逆向恢复，
--       本脚本根据 database/smart_restaurant.sql 的初始化数据重写正确值。
-- 同时清理浏览器测试期间残留的 CRUDxxxx 测试记录。
-- =====================================================================

USE `smart_restaurant`;
SET NAMES utf8mb4;

-- ---------------------------------------------------------------------
-- 1. 修复 dish 表乱码数据
-- ---------------------------------------------------------------------
-- id=1 麻辣香锅（原始数据：'麻辣香锅'）
UPDATE `dish` SET
  `dish_name`    = '麻辣香锅',
  `description`  = '招牌麻辣香锅，食材丰富，麻辣鲜香'
WHERE `id` = 1 AND HEX(`dish_name`) = '3F3F3F3F3F3F3F';

-- ---------------------------------------------------------------------
-- 2. 修复 member 表乱码数据
-- ---------------------------------------------------------------------
-- id=1 张小明（real_name 已损坏为 '?????'）
UPDATE `member` SET
  `real_name` = '张小明'
WHERE `id` = 1 AND HEX(`real_name`) = '3F3F3F3F3F';

-- ---------------------------------------------------------------------
-- 3. 清理 dish 表 CRUD 测试残留（id=20、24 是浏览器测试留下的记录）
-- ---------------------------------------------------------------------
DELETE FROM `dish` WHERE `id` IN (20, 24);

-- ---------------------------------------------------------------------
-- 4. 清理 member 表 CRUD 测试残留（id=6..15 的 CRUDxxxxM-UPD 记录，以及 id=11 的乱码记录）
-- ---------------------------------------------------------------------
DELETE FROM `member` WHERE `id` BETWEEN 6 AND 15;

-- ---------------------------------------------------------------------
-- 5. 修复完成校验：检查是否还有 '?' 字符（0x3F 重复 >=3 次的字符串）
-- ---------------------------------------------------------------------
-- 校验 dish
SELECT 'dish_check' AS tbl, COUNT(*) AS bad_rows
FROM `dish` WHERE `dish_name` REGEXP '[?]{3,}';

-- 校验 member
SELECT 'member_check' AS tbl, COUNT(*) AS bad_rows
FROM `member` WHERE `real_name` REGEXP '[?]{3,}' OR `nickname` REGEXP '[?]{3,}';

-- ---------------------------------------------------------------------
-- 6. 字符集最终状态校验
-- ---------------------------------------------------------------------
SELECT
  TABLE_NAME,
  TABLE_COLLATION
FROM information_schema.TABLES
WHERE TABLE_SCHEMA = 'smart_restaurant'
  AND TABLE_TYPE = 'BASE TABLE'
ORDER BY TABLE_NAME;
